export const FONT_METRICS: Record<string, FontMetrics> = {
	'Fredoka-Bold': FREDOKA_BOLD,
	'Fredoka-SemiBold': FREDOKA_SEMIBOLD,
	'SpaceGrotesk-Bold': SPACEGROTESK_BOLD,
	'SpaceGrotesk-Medium': SPACEGROTESK_MEDIUM
};

/** Advance width of `ch` in ems for the given bundled font family. */
export function glyphAdvance(fontFamily: string, ch: string): number {
	const metrics = FONT_METRICS[fontFamily];
	if (!metrics || !ch) return 0.62;
	const code = ch.codePointAt(0) ?? 0;
	if (code >= ASCII_START && code <= ASCII_END) {
		return metrics.ascii[code - ASCII_START] / 1000;
	}
	const extra = metrics.extra[code];
	return extra !== undefined ? extra / 1000 : metrics.avg;
}
