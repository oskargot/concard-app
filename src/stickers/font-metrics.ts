/**
 * Advance widths for the bundled sticker fonts, as thousandths of an em.
 *
 * Generated from the TTFs in `assets/fonts` so fandom stickers can fit text
 * without measuring on the UI thread. Values are integer thousandths; divide
 * by 1000 at use. Latin-1 plus a few punctuation extras cover fandom names.
 */

export interface FontMetrics {
	/** Distance from baseline to the top of the em box, in ems. */
	ascender: number;
	/** Distance from baseline to the bottom of the em box, in ems (negative). */
	descender: number;
	/** Fallback advance when a character is missing from `ascii` / `extra`. */
	avg: number;
	/** Advances for char codes 32..126 inclusive. */
	ascii: readonly number[];
	/** Sparse advances for non-ASCII glyphs we actually ship. */
	extra: Readonly<Record<number, number>>;
}

