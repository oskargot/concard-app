/**
 * Generate src/card/link-icons.ts from the `simple-icons` package.
 *
 *     node scripts/make-link-icons.mjs
 *
 * Card spec §3.5: link pill icons are Simple Icons (CC0, monochrome SVG)
 * bundled with the app, so they work offline and tint to the card's dim text
 * colour on any face. Only the platforms `src/card/link-platforms.ts` knows are
 * copied, rather than importing the whole ~3,400-icon set into the bundle.
 *
 * `simple-icons` is a devDependency: the app ships the generated paths, never
 * the package. Keep ICONS in step with the `icon` keys in link-platforms.ts.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as si from 'simple-icons';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'card', 'link-icons.ts');

/** icon key → simple-icons export. */
const ICONS = {
	instagram: 'siInstagram',
	x: 'siX',
	tiktok: 'siTiktok',
	threads: 'siThreads',
	bluesky: 'siBluesky',
	youtube: 'siYoutube',
	twitch: 'siTwitch',
	kick: 'siKick',
	github: 'siGithub',
	itchio: 'siItchdotio',
	tumblr: 'siTumblr',
	deviantart: 'siDeviantart',
	artstation: 'siArtstation',
	behance: 'siBehance',
	dribbble: 'siDribbble',
	facebook: 'siFacebook',
	reddit: 'siReddit',
	discord: 'siDiscord',
	patreon: 'siPatreon',
	kofi: 'siKofi',
	buymeacoffee: 'siBuymeacoffee',
	gumroad: 'siGumroad',
	etsy: 'siEtsy',
	kickstarter: 'siKickstarter',
	soundcloud: 'siSoundcloud',
	spotify: 'siSpotify',
	bandcamp: 'siBandcamp',
	applemusic: 'siApplemusic',
	vimeo: 'siVimeo',
	pixiv: 'siPixiv',
	linktree: 'siLinktree',
	carrd: 'siCarrd',
	substack: 'siSubstack',
	pinterest: 'siPinterest',
	snapchat: 'siSnapchat',
	telegram: 'siTelegram',
	whatsapp: 'siWhatsapp',
	mastodon: 'siMastodon',
	steam: 'siSteam'
};

const lines = [
	'/**',
	' * Link pill icons: 24 × 24 filled paths from Simple Icons (CC0).',
	' *',
	' * GENERATED by `node scripts/make-link-icons.mjs`. Do not edit by hand.',
	' * The globe for unknown domains is hand-written in `link-platforms.ts`.',
	' */',
	'',
	'export const LINK_ICONS: Readonly<Record<string, { title: string; path: string }>> = {'
];
const missing = [];
for (const [key, name] of Object.entries(ICONS)) {
	const icon = si[name];
	if (!icon) {
		missing.push(`${key} (${name})`);
		continue;
	}
	lines.push(
		`\t${key}: { title: ${JSON.stringify(icon.title)}, path: ${JSON.stringify(icon.path)} },`
	);
}
lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');
lines.push('};', '');

writeFileSync(OUT, lines.join('\r\n'));
console.log(`wrote ${Object.keys(ICONS).length - missing.length} icons to src/card/link-icons.ts`);
if (missing.length) {
	console.log(`missing from simple-icons (will draw the globe): ${missing.join(', ')}`);
	process.exitCode = 1;
}
